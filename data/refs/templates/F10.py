# 10 деревьев на бутстреп-выборках дали оценки P(красный | X); голосование большинством и усреднение
# вероятностей могут дать РАЗНЫЕ классы (в ISLR: 6 голосов за «красный», но средняя вероятность 0,45).
# ВОЗЬМИТЕ СВОИ вероятности (с тем же эффектом расхождения или без — решите сами) и добавьте отвлекающие числа
# (глубина деревьев, время обучения, accuracy на обучении, OOB-ошибка другого запуска).
# Ответ (answer_kind: numbers): средняя вероятность класса «красный» и доля деревьев, проголосовавших за «красный».
probs = None      # например [0.1, 0.15, ...] — 9–11 чисел, лучше нечётное число деревьев

if probs is None:
    raise SystemExit("Впишите свои probs")
mean_p = sum(probs) / len(probs)
vote_share = sum(p > 0.5 for p in probs) / len(probs)
print(f"# усреднение → {'красный' if mean_p > 0.5 else 'зелёный'}; голосование → {'красный' if vote_share > 0.5 else 'зелёный'}")
print(f"REFERENCE: {mean_p:.4f}; {vote_share:.4f}")
