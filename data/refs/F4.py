# F4 — изменённая версия A4 (SVM: ширина зазора и класс точки). Пара P4 для H1.
w = (5, 12)
b = -4
x = (1, 0)

if None in (w, b, x):
    raise SystemExit("Впишите свои w, b, x")
norm = (w[0] ** 2 + w[1] ** 2) ** 0.5
width = 2 / norm                                  # расстояние между w·x+b = 1 и w·x+b = -1
f = w[0] * x[0] + w[1] * x[1] + b
cls = 1 if f > 0 else -1
assert f != 0, "Точка на разделяющей гиперплоскости — класс не определён"
if abs(abs(f) - 1) < 1e-9:
    print("# заметка: точка лежит на границе зазора (|w·x+b| = 1), как в A4 — это можно оставить намеренно")
assert abs(width - 0.4) > 0.004, "Ширина совпадает с A4 (0.4) — поменяйте w"
print(f"REFERENCE: {width:.4f}; {cls}")
